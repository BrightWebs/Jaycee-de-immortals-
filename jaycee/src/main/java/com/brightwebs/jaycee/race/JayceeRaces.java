    private static void info(String id, String group, String difficulty, String unused, int str, int spd, int magic, int aura,
                             float health, float size, Alignment alignment) {
        INFO.put(id, new Info(id, group, difficulty, str, spd, magic, aura, health, size, alignment));
        STARTING.add(id);
    }

    private static void f(String id, String line, int tier, boolean starting, boolean divine, String portrait, String[] intrinsics, E[] evolutions) {
        FORMS.put(id, new Form(id, line, tier, starting, divine, portrait));
        RACES.register(id, () -> {
            Info s = INFO.get(line);
            int t = tier - 1;
            double auraK = 0.5 + 0.2 * s.aura(), manaK = 0.5 + 0.2 * s.magic();
            Race.Properties p = new Race.Properties()
                    .tier(tier)
                    .aura(AURA_MIN[t] * auraK, AURA_MAX[t] * auraK)
                    .mana(MANA_MIN[t] * manaK, MANA_MAX[t] * manaK)
                    .health(Math.round(HEALTH[t] * s.health()))
                    .spirit(SPIRIT[t])
                    .attack(ATTACK[t] * (0.6 + 0.15 * s.strength()))
                    .attackSpeed(4.0 + 0.1 * t)
                    .speed(SPEED[t] * (0.85 + 0.04 * s.speed()))
                    .knockbackResistance(Math.min(0.9, KNOCKBACK[t] + (s.size() > 1.2 ? 0.2 : 0)))
                    .size(s.size())
                    .alignment(divine && s.alignment() == Alignment.NEUTRAL ? Alignment.HOLY : s.alignment());
            if (starting) p.starting();
            if (divine) p.divine();
            for (String i : intrinsics) p.intrinsic(Identifier.parse(i));
            for (E e : evolutions) {
                Identifier to = Identifier.fromNamespaceAndPath(JayceeMod.ID, e.target());
                var reqs = TensuraRequirements.BY_EDGE.getOrDefault(id + ">" + e.target(), TensuraRequirements.BY_TARGET.get(e.target()));
                if (reqs != null) p.evolvesTo(to, reqs); else p.evolvesTo(to, e.ep(), 0);
            }
            return new Race(p);
        });
    }

